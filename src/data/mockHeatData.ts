// Calculate normalized risk score using the formula from Slide 7:
// Risk = w1*T + w2*H + w3*S + w4*B + w5*V + w6*E
export function computeRiskScore(
  record: Pick<NeighborhoodRecord, 'airTemperature' | 'relativeHumidity' | 'landSurfaceTemperature' | 'builtEnvironmentRatio' | 'vegetationIndex' | 'vulnerabilityIndex'>,
  weights: RiskWeights = DEFAULT_WEIGHTS
): { score: number; category: RiskCategory } {
  const requiredInputs = [
    ['airTemperature', record.airTemperature],
    ['relativeHumidity', record.relativeHumidity],
    ['landSurfaceTemperature', record.landSurfaceTemperature],
    ['builtEnvironmentRatio', record.builtEnvironmentRatio],
    ['vegetationIndex', record.vegetationIndex],
    ['vulnerabilityIndex', record.vulnerabilityIndex],
  ] as const;
  const missingInputs = requiredInputs
    .filter(([, value]) => !Number.isFinite(value))
    .map(([name]) => name);

  if (missingInputs.length > 0) {
    throw new Error(`Cannot calculate heat risk: missing or invalid inputs: ${missingInputs.join(', ')}`);
  }

  // Indicator normalizations based on representative bounds:
  // Air Temp: 28°C to 44°C
  const normT = Math.min(1, Math.max(0, (record.airTemperature - 28) / (44 - 28)));
  // Humidity: 20% to 80%
  const normH = Math.min(1, Math.max(0, (record.relativeHumidity - 20) / (80 - 20)));
  // Satellite Surface Temp: 30°C to 56°C
  const normS = Math.min(1, Math.max(0, (record.landSurfaceTemperature - 30) / (56 - 30)));
  // Built Environment: 0% to 100%
  const normB = Math.min(1, Math.max(0, record.builtEnvironmentRatio / 100));
  // Vegetation gap: 1 - NDVI (0 to 1)
  const normV = Math.min(1, Math.max(0, 1 - record.vegetationIndex));
  // Vulnerability index: 0 to 100
  const normE = Math.min(1, Math.max(0, record.vulnerabilityIndex / 100));

  const totalWeight = weights.airTemp + weights.humidity + weights.surfaceTemp + weights.builtEnvironment + weights.vegetationGap + weights.vulnerability;
  
  const rawWeighted = (
    weights.airTemp * normT +
    weights.humidity * normH +
    weights.surfaceTemp * normS +
    weights.builtEnvironment * normB +
    weights.vegetationGap * normV +
    weights.vulnerability * normE
  ) / (totalWeight || 1);

  const score = Math.round(rawWeighted * 100);

  let category: RiskCategory = 'Lower';
  if (score >= 75) {
    category = 'High';
  } else if (score >= 50) {
    category = 'Elevated';
  } else if (score >= 25) {
    category = 'Moderate';
  } else {
    category = 'Lower';
  }

  return { score, category };
}

