export const DEFAULT_WEIGHTS: RiskWeights = {
  airTemp: 0.20,
  humidity: 0.15,
  surfaceTemp: 0.25,
  builtEnvironment: 0.15,
  vegetationGap: 0.15,
  vulnerability: 0.10,
};

